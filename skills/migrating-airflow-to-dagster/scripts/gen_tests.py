"""Generated pytest files for converted DAGs (written by convert_ir.py, one `tests/test_<dag>.py` per converted DAG).

`render(info)` is pure: it takes facts the converter already computed for the DAG (`info`) and returns the source of the test file. What the file asserts:

* the generated module imports and its definitions load;
* every asset key, its dependencies, pool and retry policy equal what the IR said (the values are written into the test from the IR, so a hand edit of the
  generated code that drifts from the Airflow DAG fails);
* the job, and the schedule's cron and timezone;
* when the DAG has no external systems: the whole DAG materializes (`dg.materialize` on the generated assets, with the runtime's own helpers) and every
  generated asset check passes. Shell tasks run only with CONVERTED_TESTS_RUN_SHELL=1, because the test would otherwise execute arbitrary commands.
  A DAG with an external system, a sensor, a stub, partitions or assets read from outside gets the load and shape tests only, and the materialize test is a visible
  SKIP with the reason, never a pass.

Returned values are compared with Airflow's by the parity harness (it needs Airflow); these tests check outcomes and the structural asset checks.
"""
from __future__ import annotations

import json
from typing import Any


def render(info: dict[str, Any]) -> str:
    dag = info["dag_id"]
    head = f'''"""Generated by convert_ir.py from Airflow DAG `{dag}`. Structural tests only: they pin the converted definitions to the Airflow DAG's IR and, for a DAG
without external systems, run it. They are not business tests. Regenerate with the converter; do not edit the expectations by hand."""
import importlib
import os

import dagster as dg
import pytest

MODULE = {info["module"]!r}
EXPECTED_ASSETS = {info["assets"]!r}
SCHEDULE = {info.get("schedule")!r}
JOB = {info.get("job")!r}
CHECKS = {list(info.get("checks") or [])!r}
MATERIALIZE_SKIP = {info.get("materialize_skip")!r}
NEEDS_SHELL = {bool(info.get("needs_shell"))!r}
LOADABLE_ALONE = {bool(info.get("loadable_alone", True))!r}
'''
    return head + BODY


BODY = '''

def _module():
    return importlib.import_module(MODULE)


def _assets(mod):
    return [v for v in vars(mod).values() if isinstance(v, dg.AssetsDefinition) and not isinstance(v, dg.AssetChecksDefinition)]


def _checks(mod):
    return [v for v in vars(mod).values() if isinstance(v, dg.AssetChecksDefinition)]


def test_module_imports_and_definitions_load():
    mod = _module()
    if LOADABLE_ALONE:
        needed = set().union(set(), *(set(d.required_resource_keys) for d in _assets(mod) + _checks(mod)))
        defs = dg.Definitions(resources={k: dg.ResourceDefinition.mock_resource() for k in needed - {"io_manager"}}, assets=_assets(mod), asset_checks=_checks(mod), jobs=[v for v in vars(mod).values() if type(v).__name__ == "UnresolvedAssetJobDefinition"],
                              schedules=[v for v in vars(mod).values() if isinstance(v, dg.ScheduleDefinition)])
        dg.Definitions.validate_loadable(defs)


def test_asset_keys_dependencies_pool_and_retries_match_the_airflow_dag():
    mod = _module()
    got = {}
    for a in _assets(mod):
        for key in a.keys:
            got[key.to_user_string()] = (a, key)
    assert set(got) >= set(EXPECTED_ASSETS), sorted(set(EXPECTED_ASSETS) - set(got))
    for name, want in EXPECTED_ASSETS.items():
        a, key = got[name]
        if want.get("deps") is not None:
            assert sorted(d.to_user_string() for d in a.asset_deps[key]) == sorted(want["deps"]), name
        if "pool" in want:
            assert getattr(a.op, "pool", None) == want["pool"], name
        rp = a.op.retry_policy
        if want.get("retries"):
            assert rp is not None and rp.max_retries == want["retries"], name
        elif "retries" in want:
            assert rp is None or not rp.max_retries, name


def test_job_and_schedule_match_the_airflow_dag():
    mod = _module()
    jobs = [v for v in vars(mod).values() if type(v).__name__ == "UnresolvedAssetJobDefinition"]
    assert [j.name for j in jobs] == [JOB]
    scheds = [v for v in vars(mod).values() if isinstance(v, dg.ScheduleDefinition)]
    if SCHEDULE == "unchecked":
        pass
    elif SCHEDULE is None:
        assert not scheds
    else:
        assert [s.cron_schedule for s in scheds] == [SCHEDULE["cron"]] and [s.execution_timezone for s in scheds] == [SCHEDULE["timezone"]]


def test_asset_checks_are_the_generated_structural_ones():
    mod = _module()
    got = sorted(n for c in _checks(mod) for n in [k.name for k in c.check_keys])
    assert got == sorted(c["name"] for c in CHECKS)


@pytest.mark.skipif(MATERIALIZE_SKIP is not None, reason=MATERIALIZE_SKIP or "")
@pytest.mark.skipif(NEEDS_SHELL and os.environ.get("CONVERTED_TESTS_RUN_SHELL") != "1",
                    reason="the DAG runs shell commands; set CONVERTED_TESTS_RUN_SHELL=1 to run them here")
def test_dag_materializes_and_every_structural_check_passes():
    mod = _module()
    defs = dg.Definitions(assets=_assets(mod), asset_checks=_checks(mod))
    result = defs.resolve_implicit_global_asset_job_def().execute_in_process(raise_on_error=False)
    assert result.success, [str(e.event_specific_data.error)[:300] for e in result.get_step_failure_events()]
    done = {e.asset_key.to_user_string() for e in result.all_events if e.event_type_value == "ASSET_MATERIALIZATION"}
    assert done >= set(EXPECTED_ASSETS), sorted(set(EXPECTED_ASSETS) - done)
    evals = [e.event_specific_data for e in result.all_events if e.event_type_value == "ASSET_CHECK_EVALUATION"]
    assert len(evals) == len(CHECKS)
    assert all(ev.passed for ev in evals), [(ev.check_name, ev.metadata) for ev in evals if not ev.passed]
'''


def render_rewrite(info: dict[str, Any]) -> str:
    """The test file for a REWRITTEN DAG (`accept_rewrite.py` writes it). The rewrite chooses its own asset keys, so the contract is behavioural: the module loads, a job named
    after the DAG exists, the schedule's cron and timezone equal the Airflow DAG's, and (for a DAG without external systems) the whole DAG materializes and every asset check passes."""
    head = f'''"""Generated by accept_rewrite.py for the rewrite of Airflow DAG `{info["dag_id"]}`. Behavioural contract, not a key-for-key one: the rewrite picks its own asset keys."""
import importlib
import os

import dagster as dg
import pytest

MODULE = {info["module"]!r}
SCHEDULE = {info.get("schedule")!r}
JOB = {info["dag_id"]!r}
MATERIALIZE_SKIP = {info.get("materialize_skip")!r}
NEEDS_SHELL = {bool(info.get("needs_shell"))!r}
'''
    return head + '''

def _mod():
    return importlib.import_module(MODULE)


def _assets(mod):
    return [v for v in vars(mod).values() if isinstance(v, dg.AssetsDefinition) and not isinstance(v, dg.AssetChecksDefinition)]


def _checks(mod):
    return [v for v in vars(mod).values() if isinstance(v, dg.AssetChecksDefinition)]


def test_module_loads_with_assets():
    mod = _mod()
    assert _assets(mod), "the rewrite defines no asset"


def test_job_and_schedule_match_the_airflow_dag():
    mod = _mod()
    jobs = [v for v in vars(mod).values() if type(v).__name__ in ("UnresolvedAssetJobDefinition", "JobDefinition")]
    assert JOB in [j.name for j in jobs], [j.name for j in jobs]
    scheds = [v for v in vars(mod).values() if isinstance(v, dg.ScheduleDefinition)]
    if SCHEDULE is None:
        assert not scheds
    else:
        assert [(s.cron_schedule, s.execution_timezone) for s in scheds] == [(SCHEDULE["cron"], SCHEDULE["timezone"])]


@pytest.mark.skipif(MATERIALIZE_SKIP is not None, reason=MATERIALIZE_SKIP or "")
@pytest.mark.skipif(NEEDS_SHELL and os.environ.get("CONVERTED_TESTS_RUN_SHELL") != "1", reason="the DAG runs shell commands; set CONVERTED_TESTS_RUN_SHELL=1 to run them here")
def test_dag_materializes_and_every_check_passes():
    mod = _mod()
    defs = dg.Definitions(assets=_assets(mod), asset_checks=_checks(mod))
    result = defs.resolve_implicit_global_asset_job_def().execute_in_process(raise_on_error=False)
    assert result.success, [str(e.event_specific_data.error)[:300] for e in result.get_step_failure_events()]
    evals = [e.event_specific_data for e in result.all_events if e.event_type_value == "ASSET_CHECK_EVALUATION"]
    assert all(ev.passed for ev in evals), [(ev.check_name, ev.metadata) for ev in evals if not ev.passed]
'''
