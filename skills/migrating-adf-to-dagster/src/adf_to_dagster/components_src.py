"""Source of the generated project's components.py.

SSIS, Synapse, Fabric and SQL copy use the registry components as they are (declared items, `dry_run` from ADF_DRY_RUN). Only
`warehouse_pipeline` has no `dry_run`, so a data flow translated to SQL steps goes through a thin subclass that logs instead of running.
"""

COMPONENTS_SOURCE = '''"""Registry components that honor ADF_DRY_RUN=1 (generated by adf-to-dagster)."""
from __future__ import annotations

import os

import dagster as dg
import dagster_community_components as _dcc

# The package exports lazy placeholders: a subclass of one fails. Subclass the real classes. A component whose extra dependencies are not installed (the Synapse
# SDKs, for example) comes back as a placeholder object instead of a class; its Adf subclass is then simply not defined, and a project that needs it lists the
# dependency (the generated pyproject does).
def _real(name):
    try:
        cls = _dcc._load_real_class(name)
    except Exception:                                  # noqa: BLE001
        return None
    return cls if isinstance(cls, type) else None


WarehousePipelineComponent = _real("WarehousePipelineComponent")


def _dry() -> bool:
    return os.environ.get("ADF_DRY_RUN") == "1"


def _logged(defs: dg.Definitions) -> dg.Definitions:
    """The same assets with a body that logs instead of running."""
    specs = [s for a in defs.assets or [] if isinstance(a, dg.AssetsDefinition) for s in a.specs]
    if not specs:
        return defs

    first = specs[0].key.to_user_string()

    @dg.multi_asset(name="dry_" + "".join(ch if ch.isalnum() else "_" for ch in first), specs=specs, can_subset=True)
    def _dry_assets(context):                # no annotation: under `from __future__ import annotations` dagster cannot resolve a dotted one
        for key in context.selected_asset_keys:
            context.log.info(f"DRY RUN, not executed: {key.to_user_string()}")
            yield dg.MaterializeResult(asset_key=key)

    return dg.Definitions(assets=[_dry_assets])


if WarehousePipelineComponent is not None:
    class AdfWarehousePipelineComponent(WarehousePipelineComponent):
        """WarehousePipelineComponent that, in a dry run, logs instead of running the CTAS (a Mapping Data Flow translated to SQL steps)."""

        def build_defs(self, context: dg.ComponentLoadContext) -> dg.Definitions:
            defs = super().build_defs(context)
            return _logged(defs) if _dry() else defs
'''
